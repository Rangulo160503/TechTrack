export function homeRows(assets: InventoryAsset[]): { title: string; items: InventoryAsset[] }[] {
  const recientes = assets.slice(0, 6)
  const mantenimiento = assets.filter((a) => a.status === 'InMaintenance' || a.status === 'OutOfService')
  const lab = assets.filter((a) => a.location.includes('Lab. Informática'))
  return [
    { title: 'Recientes', items: recientes },
    { title: 'En mantenimiento', items: mantenimiento },
    { title: 'Por ubicación · Lab. Informática', items: lab },
  ]
}
